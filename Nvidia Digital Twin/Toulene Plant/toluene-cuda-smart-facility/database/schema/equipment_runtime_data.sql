-- equipment_runtime_data.sql
-- Plant run telemetry keyed by equipment tag

create table public."Equipment Runtime Data" (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  "Equipment" text null,
  "Key output" text null,
  constraint "Equipment Runtime Data_pkey" primary key (id)
) tablespace pg_default;

create index idx_equipment_runtime_data_equipment
  on public."Equipment Runtime Data" ("Equipment");

create index idx_equipment_runtime_data_created_at
  on public."Equipment Runtime Data" (created_at desc);
